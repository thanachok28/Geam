// ฟังก์ชันช่วยดึง Google Apps Script URL ปัจจุบัน (ลำดับ: LocalStorage -> Default)
function getGasWebAppUrl() {
  const customUrl = localStorage.getItem('HISTORY_GAME_GAS_URL');
  if (customUrl && customUrl.trim().length > 0) {
    return customUrl.trim();
  }
  return GAME_CONFIG.DEFAULT_GAS_WEBAPP_URL.trim();
}

// ฟังก์ชันช่วยบันทึก GAS URL ใหม่ลง LocalStorage
function saveGasWebAppUrl(url) {
  if (url && url.trim().length > 0) {
    localStorage.setItem('HISTORY_GAME_GAS_URL', url.trim());
    return true;
  } else {
    localStorage.removeItem('HISTORY_GAME_GAS_URL');
    return false;
  }
}
